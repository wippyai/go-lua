// Package static owns the Link's sealed static inventory: the judgment one
// authored static type reaches and the value classification those judgments
// are compared under.
//
// # What the domain owns
//
// One sealed authority and the algebras it carries.
//
//   - The result algebra. A judgment is closed, symbolic, or invalid, with a
//     bottom and a top that exist only so the result can sit in a sparse factor
//     carrier. A closed judgment retains its owner-issued canonical identity;
//     a symbolic one retains a finite residual equation with the reason it
//     stayed residual; an invalid one retains the structured site and the fault
//     that named it.
//   - The classification. A ClassSet holds the sealed singleton rows and the
//     owner-fenced lower-set descriptors derived from them, with the coverage
//     identity, rank, and nil admission every relational judgment is recomputed
//     against by finite scan.
//   - The authored-side coordinates a judgment is keyed by: the type reference,
//     mounted namespace, type-argument sequence identity, and detached operand
//     disposition the evaluator issues.
//
// Everything above is sealed once, before the mount phase opens, and is
// immutable afterwards. The domain runs no fixpoint and holds no solver state.
//
// # Declaration
//
// This domain declares no row on any surface of the analyzer declaration table.
// The reason is one reason stated eight times, because a surface with nothing to
// declare is a surface this domain says nothing about rather than one it has not
// reached yet:
//
//   - Axis. An axis is a coordinate space the solver writes during a fixpoint
//     and a Link instantiates a carrier for. The static inventory is a factor of
//     no axis: it is sealed before the mount transaction begins and enters that
//     transaction as a neutral input, so a mounting axis that seals over it names
//     it in its own need interface instead of reading a carrier. There is no
//     coordinate here to declare, and declaring one would claim a writer
//     principal for a table that is already closed when the first rule runs.
//   - Rule. A rule declares an engine slot at an artifact rule role and attaches
//     at a mount point. Nothing in this domain is bound at a mount, evaluated at
//     a point, or admitted into a receipt; the evaluation this package does is
//     the seal, not a hot factor.
//   - Diagnostic. A diagnostic row publishes a code from facts the analyzer
//     already produces. A judgment that cannot conclude is answered to its caller
//     as an invalid result carrying its fault and its structured site, which is
//     the caller's input to its own reasoning rather than a published finding.
//     The fault vocabulary is the invalid judgment's identity, and no code in the
//     analyzer is issued from it.
//   - Composite. A composite is a relation over declared coordinate spaces, and
//     every axis it names must resolve. This domain names none.
//   - Denominator. A denominator names the surface entry whose universe it
//     quantifies over, and that owner must be an entry on a surface sealed below
//     the denominator surface. This domain owns no entry, so it has nothing to
//     close a world around. Its finite descriptor universe is closed by
//     construction inside one sealed authority, and a denominator over a table
//     that is already total states nothing the seal has not.
//   - Query. A query family reads declared coordinate spaces and publishes a
//     result codec. This domain reads no coordinate space and publishes no
//     solver-visible result: its readers hold its handles directly.
//   - Structure. The structural vocabulary hosts the closed catalogs the analyzer
//     would otherwise spell once per consumer. This domain has five closed
//     enumerations: the result algebra, the symbolic reason, the invalid fault,
//     the operand disposition, and the class row kind. Four of them have exactly
//     one reader, this package, so there is no second spelling for a declaration
//     to hold them against, and a member that acquires a reader outside this
//     package acquires a reason to be declared at the same time. The operand
//     disposition is the exception and is recorded below rather than declared,
//     because what it needs first is a decision, not a row.
//   - Library. A library contract kind addresses exported values under a member
//     form algebra. This domain publishes no exported value; the contract
//     representation its judgments are authored from is owned by the type domain.
//
// The zero-row statement is executable. A surface of the declaration table is
// reached by importing its package, so a domain that declares no row imports no
// surface, and the declaration law states exactly that. A row added here
// therefore cannot be added without this file being rewritten in the same
// change.
//
// # Second spellings
//
// One restatement remains, and it is recorded here rather than declared away,
// because it needs an owner's decision before a row could be honest about it:
//
//   - The operand disposition is spelled twice. This package spells it as the
//     evaluator's four-member disposition, and the compiled artifact spells it
//     as the Program-issued row disposition, and the two do not name the same
//     members: the evaluator has an unknown disposition the artifact does not
//     issue, and the artifact issues a typevalue disposition the evaluator
//     collapses into known while sealing. The collapse is the seal's own
//     translation, so nothing downstream sees the disagreement, but the two
//     member lists are a divergence in subject matter rather than a wiring gap,
//     and a structural row would have to pick one of them to be the vocabulary.
//
// # Consumers
//
// The sealed authority enters the mount transaction as a neutral input. The
// pack axis is its reader there. Program-side callers hold the authority
// directly, from the seal that produced it.
