package gen

import (
	"bytes"
	"fmt"
	"go/format"

	"github.com/wippyai/go-lua/analysis/semantic/inventory"
)

const generatedHeader = "// Code generated by analysis/semantic/inventory; DO NOT EDIT.\n"

func RenderState(in inventory.Inventory, bindings Bindings) ([]byte, error) {
	lanes, _, err := orderedBindings(in, bindings)
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString(generatedHeader)
	out.WriteString("package state\n\n")
	out.WriteString("var defaultLaneCatalog = newLaneCatalog([]laneSpec{\n")
	for _, lane := range lanes {
		fmt.Fprintf(&out, "\t%s,\n", lane.SpecSymbol)
	}
	out.WriteString("})\n\nvar (\n")
	for _, lane := range lanes {
		fmt.Fprintf(&out, "\t%s = defaultLaneCatalog.mustLaneBit(%s)\n", lane.BitSymbol, lane.IDSymbol)
	}
	out.WriteString(")\n")
	return formatted("state lane inventory", out.Bytes())
}

func RenderService(in inventory.Inventory, bindings Bindings) ([]byte, error) {
	_, valueAxes, err := orderedBindings(in, bindings)
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString(generatedHeader)
	out.WriteString("package service\n\nimport (\n")
	out.WriteString("\t\"github.com/wippyai/go-lua/analysis/domain/value/axis\"\n")
	for _, valueAxis := range valueAxes {
		fmt.Fprintf(&out, "\t%s %q\n", valueAxis.Alias, valueAxis.ImportPath)
	}
	out.WriteString("\t\"github.com/wippyai/go-lua/analysis/domain/value/product\"\n")
	out.WriteString(")\n\nvar checkerRegistry = mustCheckerRegistry()\n\n")
	out.WriteString("func mustCheckerRegistry() *axis.Registry {\n")
	out.WriteString("\tregistry, err := product.RegistryWithAxes(\n")
	for _, valueAxis := range valueAxes {
		fmt.Fprintf(&out, "\t\t%s.%s().Erase(),\n", valueAxis.Alias, valueAxis.SpecSymbol)
	}
	out.WriteString("\t)\n\tif err != nil {\n\t\tpanic(err)\n\t}\n\treturn registry\n}\n")
	return formatted("service value registry", out.Bytes())
}

func formatted(label string, source []byte) ([]byte, error) {
	out, err := format.Source(source)
	if err != nil {
		return nil, fmt.Errorf("format generated %s: %w", label, err)
	}
	return out, nil
}
