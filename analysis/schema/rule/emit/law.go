// The laws a generated member set owes are laws about the generated code and
// about nothing else. What order it answers in, that it holds one member per
// coordinate, and that an ordinary answer costs no allocation are all decided
// by the construction this package writes - no fact any domain supplies
// reaches them - so the generator that writes the construction writes their
// laws beside it, rather than leaving every migrated owner to restate the same
// three by hand and get one of them quietly wrong.

// RenderLaw projects one rule declaration's generated construction into the law
// suite that construction owes. It answers nil for a declaration with no
// generated construction: a family whose relations are authored has nothing
// here for a law to hold, and an empty suite would state only that the
// generator ran.
func RenderLaw(target Target, roster definition.Roster) ([]byte, error) {
	if !target.available() {
		return nil, errors.New("rule family emitter: target package and rule declaration are required")
	}
	built, err := derive(target, roster)
	if err != nil {
		return nil, err
	}
	derivations := declaredDerivations(built)
	if len(derivations) == 0 {
		return nil, nil
	}
	imports := built.imports
	imports.reserve(built.target.PackageName)
	testing := imports.use("testing")
	var body strings.Builder
	for _, join := range derivations {
		renderDerivedLaws(&body, built, join.derivation.declared, testing)
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by the rule family emitter from the %q rule declaration; DO NOT EDIT.\n",
		string(built.target.Spec.Key))
	out.WriteString("//\n")
	out.WriteString("// These are the laws the generated construction beside this file owes by\n")
	out.WriteString("// construction: the order it answers its members in, that it holds one member\n")
	out.WriteString("// per coordinate, and that an answer within the declared inline width costs no\n")
	out.WriteString("// allocation. None of the three is knowledge about the fold, and none of them\n")
	out.WriteString("// reaches a fact any domain supplies, so a family authors beside them only the\n")
	out.WriteString("// laws that say what its own judgment MEANS.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", built.target.PackageName)
	out.WriteString(imports.block())
	out.WriteString(body.String())
	formatted, formatErr := format.Source([]byte(out.String()))
	if formatErr != nil {
		return nil, fmt.Errorf("rule family emitter: rule %q: format generated law suite: %w", string(target.Spec.Key), formatErr)
	}
	return formatted, nil
}

// renderDerivedLaws writes the three laws one generated member set owes.
func renderDerivedLaws(out *strings.Builder, built *plan, declared *declaredPlan, testing string) {
	imports := built.imports
	subject := imports.typeName(declared.subject)
	dense := imports.typeName(declared.order.normalized)
	tag := imports.typeName(declared.predicateType)
	state := declared.state()
	width := derivedWidthName(declared.position)
	insert := derivedInsertName(declared.position)
	count := derivedCountName(declared.position)
	at := derivedAtName(declared.position)
	memberAt := derivedMemberAtName(declared.position)
	sink := derivedSinkName(declared.position)
	suffix := strings.ToUpper(state[:1]) + state[1:]

	fmt.Fprintf(out, "// %s keeps the measured construction from being elided. It holds a\n", sink)
	out.WriteString("// count rather than the set itself: a set that escaped to a package variable\n")
	out.WriteString("// would allocate for that reason alone, and the law would be measuring its own\n")
	out.WriteString("// instrument.\n")
	fmt.Fprintf(out, "var %s int\n\n", sink)

	fmt.Fprintf(out, "// Test%sAnswersItsMembersInCoordinateOrder states the one admissible\n", suffix)
	out.WriteString("// order of a member set. The engine canonicalizes a selection by the coordinate\n")
	out.WriteString("// its cells are read at, so members arriving in any order are answered\n")
	out.WriteString("// ascending by that coordinate - across the spill exactly as within the inline\n")
	out.WriteString("// prefix, because the two are one set and not two.\n")
	fmt.Fprintf(out, "func Test%sAnswersItsMembersInCoordinateOrder(t *%s.T) {\n", suffix, testing)
	fmt.Fprintf(out, "\tvar row %s\n\tvar built %s\n", subject, state)
	out.WriteString("\t// Twice the inline width, so the spill is ordered against the prefix and not\n")
	out.WriteString("\t// merely beside it, and descending, so every member is placed in front of the\n")
	out.WriteString("\t// ones already held.\n")
	fmt.Fprintf(out, "\tfor coordinate := 2 * %s; coordinate > 0; coordinate-- {\n", width)
	out.WriteString("\t\tvar placed bool\n")
	fmt.Fprintf(out, "\t\tbuilt, placed = %s(built, %s(coordinate), %s(coordinate), row)\n", insert, dense, tag)
	out.WriteString("\t\tif !placed {\n\t\t\tt.Fatalf(\"the member at coordinate %d was refused by its own set\", coordinate)\n\t\t}\n\t}\n")
	fmt.Fprintf(out, "\tif got, want := %s(built), 2*%s; got != want {\n", count, width)
	out.WriteString("\t\tt.Fatalf(\"the set holds %d members, want %d\", got, want)\n\t}\n")
	fmt.Fprintf(out, "\tfor index := 0; index < %s(built); index++ {\n", count)
	fmt.Fprintf(out, "\t\tmember, memberOK := %s(built, index)\n", memberAt)
	out.WriteString("\t\tif !memberOK {\n\t\t\tt.Fatalf(\"ordinal %d of the set is unreadable\", index)\n\t\t}\n")
	fmt.Fprintf(out, "\t\tif want := %s(index + 1); member.dense != want {\n", dense)
	out.WriteString("\t\t\tt.Fatalf(\"ordinal %d is at coordinate %d, want %d\", index, member.dense, want)\n\t\t}\n")
	fmt.Fprintf(out, "\t\tif _, rowOK := %s(built, index); !rowOK {\n", at)
	out.WriteString("\t\t\tt.Fatalf(\"ordinal %d holds a coordinate but no member\", index)\n\t\t}\n\t}\n}\n\n")

	fmt.Fprintf(out, "// Test%sHoldsOneMemberPerAddress is the other half of the order.\n", suffix)
	out.WriteString("// A member is reached at a coordinate and at the tag its predicate answers,\n")
	out.WriteString("// and that pair is its whole address. An item resolving to an address the set\n")
	out.WriteString("// already holds is the same member named twice and adds no ordinal; two\n")
	out.WriteString("// members on one coordinate under different tags are two cells where a\n")
	out.WriteString("// selection carries one, and have no answer.\n")
	fmt.Fprintf(out, "func Test%sHoldsOneMemberPerAddress(t *%s.T) {\n", suffix, testing)
	fmt.Fprintf(out, "\tvar row %s\n", subject)
	fmt.Fprintf(out, "\tbuilt, placed := %s(%s{}, 1, 1, row)\n", insert, state)
	out.WriteString("\tif !placed {\n\t\tt.Fatal(\"the first member of a set was refused\")\n\t}\n")
	fmt.Fprintf(out, "\taliased, aliasedOK := %s(built, 1, 1, row)\n", insert)
	fmt.Fprintf(out, "\tif !aliasedOK || %s(aliased) != 1 {\n", count)
	out.WriteString("\t\tt.Fatal(\"one member named twice was taken as two, or refused\")\n\t}\n")
	fmt.Fprintf(out, "\tif _, contended := %s(built, 1, 2, row); contended {\n", insert)
	out.WriteString("\t\tt.Fatal(\"two members on one coordinate were admitted; a selection carries one cell there\")\n\t}\n}\n\n")

	fmt.Fprintf(out, "// Test%sFillsItsDeclaredWidthWithoutAllocating is the migration bar\n", suffix)
	out.WriteString("// this construction was written to. The authored derivations it replaces are\n")
	out.WriteString("// allocation-free on a solve path, so an answer within the width its relation\n")
	out.WriteString("// declares is held by value and costs nothing at all.\n")
	fmt.Fprintf(out, "func Test%sFillsItsDeclaredWidthWithoutAllocating(t *%s.T) {\n", suffix, testing)
	fmt.Fprintf(out, "\tvar row %s\n", subject)
	fmt.Fprintf(out, "\tallocations := %s.AllocsPerRun(64, func() {\n", testing)
	fmt.Fprintf(out, "\t\tvar built %s\n", state)
	fmt.Fprintf(out, "\t\tfor coordinate := %s; coordinate > 0; coordinate-- {\n", width)
	out.WriteString("\t\t\tvar placed bool\n")
	fmt.Fprintf(out, "\t\t\tbuilt, placed = %s(built, %s(coordinate), %s(coordinate), row)\n", insert, dense, tag)
	out.WriteString("\t\t\tif !placed {\n\t\t\t\treturn\n\t\t\t}\n\t\t}\n")
	fmt.Fprintf(out, "\t\t%s += %s(built)\n\t})\n", sink, count)
	out.WriteString("\tif allocations != 0 {\n")
	out.WriteString("\t\tt.Fatalf(\"one answer within the declared inline width cost %v allocations; a derived member set is held by value\", allocations)\n\t}\n")
	fmt.Fprintf(out, "\tif %s == 0 {\n", sink)
	out.WriteString("\t\tt.Fatal(\"the measured construction never completed, so the allocation law measured nothing\")\n\t}\n}\n\n")
}

// GenerateLaw writes one rule's emitted construction laws, or proves the
// checked-in file is already the one the declaration derives when check is
// true. A declaration with no generated construction owes no file, and one
// left behind by a declaration that stopped having one is stale in exactly the
// way a stale family is.
func GenerateLaw(target Target, roster definition.Roster, path string, check bool) error {
	if path == "" {
		return errors.New("rule family emitter: output path is required")
	}
	source, err := RenderLaw(target, roster)
	if err != nil {
		return err
	}
	if source == nil {
		return absentLaw(path, check)
	}
	if check {
		return freshLaw(path, source)
	}
	if err := os.WriteFile(path, source, 0o644); err != nil {
		return fmt.Errorf("rule family emitter: write %s: %w", path, err)
	}
	return nil
}

func absentLaw(path string, check bool) error {
	if _, err := os.Stat(path); err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("rule family emitter: stat %s: %w", path, err)
	}
	if check {
		return fmt.Errorf("rule family emitter: generated law suite for a family with no generated construction: %s", path)
	}
	if err := os.Remove(path); err != nil {
		return fmt.Errorf("rule family emitter: remove %s: %w", path, err)
	}
	return nil
}

func freshLaw(path string, want []byte) error {
	got, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("rule family emitter: read %s: %w", path, err)
	}
	if !bytes.Equal(got, want) {
		return fmt.Errorf("rule family emitter: stale generated law suite: %s", path)
	}
	return nil
}
