package census

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/wippyai/go-lua/analysis/lua/parsersource"
)

// Generate rebuilds or checks the compact parser/AST census. Existing
// grammarproof evidence is intentionally not touched by this generator.
func Generate(root, out string, check bool) error {
	if filepath.Base(out) != "census_gen.go" {
		return fmt.Errorf("parser census: out must name census_gen.go, got %s", filepath.Base(out))
	}
	value, err := Build(root)
	if err != nil {
		return err
	}
	rendered, err := render(value)
	if err != nil {
		return err
	}
	if check {
		current, readErr := os.ReadFile(out)
		if readErr != nil || !bytes.Equal(current, rendered) {
			return fmt.Errorf("parser census: generated census is stale")
		}
		return nil
	}
	if err := os.WriteFile(out, rendered, 0o644); err != nil {
		return fmt.Errorf("parser census: write generated census: %w", err)
	}
	return nil
}

func render(value Census) ([]byte, error) {
	var out strings.Builder
	out.WriteString("// Code generated by parser-census; DO NOT EDIT.\n\n")
	out.WriteString("package census\n\n")
	out.WriteString("import (\n")
	out.WriteString("\t\"github.com/wippyai/go-lua/analysis/lua/parsersource\"\n")
	out.WriteString(")\n\n")
	out.WriteString("var Generated = Census{\n")
	fmt.Fprintf(&out, "\tGrammarSourceDigest: %q,\n", value.GrammarSourceDigest)
	fmt.Fprintf(&out, "\tASTDigest: %q,\n", value.ASTDigest)
	fmt.Fprintf(&out, "\tDigest: %q,\n", value.Digest)
	out.WriteString("\tProductions: []parsersource.ActionTemplate{\n")
	for _, row := range value.Productions {
		out.WriteString("\t\t{\n")
		fmt.Fprintf(&out, "\t\t\tKey: %q, Nonterminal: %q, ResultTag: %q, Ordinal: %d,\n", row.Key, row.Nonterminal, row.ResultTag, row.Ordinal)
		writeStrings(&out, "RHS", row.RHS)
		out.WriteString(",\n")
		fmt.Fprintf(&out, "\t\t\tActionDigest: %q,\n", row.ActionDigest)
		writeStrings(&out, "Constructors", row.Constructors)
		out.WriteString(",\n\t\t},\n")
	}
	out.WriteString("\t},\n")
	out.WriteString("\tConstructors: []parsersource.Constructor{\n")
	for _, row := range value.Constructors {
		writeConstructor(&out, row)
	}
	out.WriteString("\t},\n")
	out.WriteString("\tProducts: []parsersource.ActionProduct{\n")
	for _, row := range value.Products {
		writeProduct(&out, row)
	}
	out.WriteString("\t},\n")
	out.WriteString("\tMutations: []parsersource.FieldMutation{\n")
	for _, row := range value.Mutations {
		writeMutation(&out, row)
	}
	out.WriteString("\t},\n")
	out.WriteString("\tSlots: []parsersource.UseSlot{\n")
	for _, row := range value.Slots {
		writeSlot(&out, row)
	}
	out.WriteString("\t},\n")
	out.WriteString("\tUses: []parsersource.ActionUse{\n")
	for _, row := range value.Uses {
		writeUse(&out, row)
	}
	out.WriteString("\t},\n")
	out.WriteString("\tSequences: []parsersource.ActionSequence{\n")
	for _, row := range value.Sequences {
		writeSequence(&out, row)
	}
	out.WriteString("\t},\n")
	out.WriteString("}\n")
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("parser census: format generated census: %w", err)
	}
	for line, source := range strings.Split(string(formatted), "\n") {
		if len(source) > 320 {
			return nil, fmt.Errorf("parser census: generated line %d exceeds 320 bytes", line+1)
		}
	}
	return formatted, nil
}

func writeConstructor(out *strings.Builder, row parsersource.Constructor) {
	fmt.Fprintf(out, "\t\t{Name: %q, Class: parsersource.ConstructorClass(%d), Semantic: %t, Fields: ", row.Name, row.Class, row.Semantic)
	writeFields(out, row.Fields)
	out.WriteString("},\n")
}

func writeProduct(out *strings.Builder, row parsersource.ActionProduct) {
	fmt.Fprintf(out, "\t\t{Owner: %q, Scope: parsersource.ProductScope(%d), Ordinal: %d, Constructor: %q, Guarded: %t, Rejected: %t, Elementwise: %t, Root: %t, Fields: ", row.Owner, row.Scope, row.Ordinal, row.Constructor, row.Guarded, row.Rejected, row.Elementwise, row.Root)
	writeProductFields(out, row.Fields)
	out.WriteString("},\n")
}

func writeProductFields(out *strings.Builder, rows []parsersource.ProductField) {
	if len(rows) == 0 {
		out.WriteString("nil")
		return
	}
	out.WriteString("[]parsersource.ProductField{\n")
	for _, row := range rows {
		fmt.Fprintf(out, "{Ordinal: %d, Field: %q, Assigned: %t, States: ", row.Ordinal, row.Field, row.Assigned)
		writeStates(out, row.States)
		out.WriteString("},\n")
	}
	out.WriteString("}")
}

func writeMutation(out *strings.Builder, row parsersource.FieldMutation) {
	fmt.Fprintf(out, "\t\t{Owner: %q, Scope: parsersource.ProductScope(%d), Constructor: %q, Field: %q, States: ", row.Owner, row.Scope, row.Constructor, row.Field)
	writeStates(out, row.States)
	out.WriteString("},\n")
}

func writeSlot(out *strings.Builder, row parsersource.UseSlot) {
	fmt.Fprintf(out, "\t\t{Form: %q, Field: %q, Class: parsersource.ConstructorClass(%d), Role: parsersource.UseRole(%d), ChildType: %q, ChildClass: parsersource.ConstructorClass(%d), Cardinality: %d},\n",
		row.Form, row.Field, row.Class, row.Role, row.ChildType, row.ChildClass, row.Cardinality)
}

func writeUse(out *strings.Builder, row parsersource.ActionUse) {
	fmt.Fprintf(out, "\t\t{Owner: %q, Scope: parsersource.ProductScope(%d), Ordinal: %d, Form: %q, Field: %q, Origins: ", row.Owner, row.Scope, row.Ordinal, row.Form, row.Field)
	writeOrigins(out, row.Origins)
	out.WriteString(", Sources: ")
	writeOrdinals(out, row.Sources)
	out.WriteString(", Symbols: ")
	writeOrdinals(out, row.Symbols)
	out.WriteString("},\n")
}

func writeSequence(out *strings.Builder, row parsersource.ActionSequence) {
	fmt.Fprintf(out, "\t\t{Production: %q, Tag: %q, Field: %q, Construction: parsersource.SequenceConstruction(%d), Segments: ", row.Production, row.Tag, row.Field, row.Construction)
	writeSegments(out, row.Segments)
	out.WriteString("},\n")
}

// writeSegments keeps the difference between a construction that states no
// operands and one that states an empty list of them. The first is a reduction
// which leaves the carrier alone; the second is a reduction which builds a list
// of length zero, and a renderer that spelled both as nil would let one be read
// as the other.
func writeSegments(out *strings.Builder, rows []parsersource.SequenceSegment) {
	if rows == nil {
		out.WriteString("nil")
		return
	}
	if len(rows) == 0 {
		out.WriteString("[]parsersource.SequenceSegment{}")
		return
	}
	out.WriteString("[]parsersource.SequenceSegment{\n")
	for _, row := range rows {
		fmt.Fprintf(out, "{Ordinal: %d, Kind: parsersource.SequenceSegmentKind(%d), Origins: ", row.Ordinal, row.Kind)
		writeOrigins(out, row.Origins)
		out.WriteString(", Sources: ")
		writeOrdinals(out, row.Sources)
		out.WriteString(", Symbols: ")
		writeOrdinals(out, row.Symbols)
		out.WriteString("},\n")
	}
	out.WriteString("}")
}

func writeOrigins(out *strings.Builder, rows []parsersource.UseOrigin) {
	if len(rows) == 0 {
		out.WriteString("nil")
		return
	}
	out.WriteString("[]parsersource.UseOrigin{")
	for _, row := range rows {
		fmt.Fprintf(out, "%d,", row)
	}
	out.WriteString("}")
}

func writeOrdinals(out *strings.Builder, rows []int) {
	if len(rows) == 0 {
		out.WriteString("nil")
		return
	}
	out.WriteString("[]int{")
	for _, row := range rows {
		fmt.Fprintf(out, "%d,", row)
	}
	out.WriteString("}")
}

func writeStates(out *strings.Builder, rows []parsersource.FieldState) {
	if len(rows) == 0 {
		out.WriteString("nil")
		return
	}
	out.WriteString("[]parsersource.FieldState{")
	for _, row := range rows {
		fmt.Fprintf(out, "%d,", row)
	}
	out.WriteString("}")
}

func writeFields(out *strings.Builder, rows []parsersource.Field) {
	if len(rows) == 0 {
		out.WriteString("nil")
		return
	}
	var compact strings.Builder
	compact.WriteString("[]parsersource.Field{")
	for _, row := range rows {
		fmt.Fprintf(&compact, "{Ordinal: %d, Name: %q, Type: %q, Form: parsersource.FieldForm(%d)},", row.Ordinal, row.Name, row.Type, row.Form)
	}
	compact.WriteString("}")
	if compact.Len() <= 140 {
		out.WriteString(compact.String())
		return
	}
	out.WriteString("[]parsersource.Field{\n")
	for _, row := range rows {
		fmt.Fprintf(out, "{Ordinal: %d, Name: %q, Type: %q, Form: parsersource.FieldForm(%d)},\n", row.Ordinal, row.Name, row.Type, row.Form)
	}
	out.WriteString("}")
}

func writeStrings(out *strings.Builder, name string, rows []string) {
	prefix := ""
	if name != "" {
		prefix = name + ": "
	}
	if len(rows) == 0 {
		out.WriteString(prefix)
		out.WriteString("nil")
		return
	}
	var compact strings.Builder
	compact.WriteString(prefix)
	compact.WriteString("[]string{")
	for _, row := range rows {
		compact.WriteString(strconv.Quote(row))
		compact.WriteByte(',')
	}
	compact.WriteString("}")
	if compact.Len() <= 200 {
		out.WriteString(compact.String())
		return
	}
	out.WriteString(prefix)
	out.WriteString("[]string{\n")
	for _, row := range rows {
		out.WriteString(strconv.Quote(row))
		out.WriteString(",\n")
	}
	out.WriteString("}")
}
