package programsupply

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"

	"github.com/wippyai/go-lua/analysis/schema"
	"github.com/wippyai/go-lua/analysis/schema/denominator"
)

// Generate rebuilds or checks the cold Program-supply evidence source.
func Generate(out string, check bool) error {
	evidence, err := Build()
	if err != nil {
		return err
	}
	rendered, err := render(evidence)
	if err != nil {
		return err
	}
	current, readErr := os.ReadFile(out)
	if check {
		if readErr != nil || !bytes.Equal(current, rendered) {
			return fmt.Errorf("program supply: evidence is stale")
		}
		return nil
	}
	if err := os.WriteFile(out, rendered, 0o644); err != nil {
		return fmt.Errorf("program supply: write evidence: %w", err)
	}
	return nil
}

func render(e Evidence) ([]byte, error) {
	var out strings.Builder
	out.WriteString("// Code generated by Program supply evidence; DO NOT EDIT.\n\npackage programsupply\n\n")
	out.WriteString("import (\n\tflowkind \"github.com/wippyai/go-lua/analysis/program/flow/kind\"\n\t\"github.com/wippyai/go-lua/analysis/lua/internal/grammarproof/requirements/binder\"\n\t\"github.com/wippyai/go-lua/analysis/lua/internal/grammarproof/requirements/programlaw\"\n\t\"github.com/wippyai/go-lua/analysis/lua/internal/grammarproof/requirements/staticlaw\"\n\t\"github.com/wippyai/go-lua/analysis/schema\"\n)\n\n")
	fmt.Fprintf(&out, "var Generated = Evidence{\n\t\tDigest: %q,\n", e.Digest)
	out.WriteString("\t\tProgramLaws: []ProgramLawRow{\n")
	for _, row := range e.ProgramLaws {
		fmt.Fprintf(&out, "\t\t\t{Requirement: programlaw.Requirement{Site: programlaw.Site(%d), Unary: flowkind.UnaryOp(%d), Binary: flowkind.BinaryOp(%d), Select: flowkind.SelectOp(%d), Call: programlaw.CallMode(%d), Values: programlaw.ValuesMode(%d), Outcome: flowkind.OutcomeKind(%d)}, Terminals: ", row.Requirement.Site, row.Requirement.Unary, row.Requirement.Binary, row.Requirement.Select, row.Requirement.Call, row.Requirement.Values, row.Requirement.Outcome)
		renderIDs(&out, row.Terminals)
		out.WriteString("},\n")
	}
	out.WriteString("\t\t},\n\t\tStaticLaws: []StaticLawRow{\n")
	for _, row := range e.StaticLaws {
		fmt.Fprintf(&out, "\t\t\t{Family: staticlaw.Family(%d), Terminals: ", row.Family)
		renderIDs(&out, row.Terminals)
		out.WriteString("},\n")
	}
	out.WriteString("\t\t},\n\t\tBinderLaws: []BinderRow{\n")
	for _, row := range e.BinderLaws {
		fmt.Fprintf(&out, "\t\t\t{Requirement: binder.Requirement{Transition: binder.Transition(%d)}, Positive: ", row.Requirement.Transition)
		renderIDs(&out, row.Positive)
		out.WriteString(", Forbidden: ")
		renderIDs(&out, row.Forbidden)
		out.WriteString("},\n")
	}
	out.WriteString("\t\t},\n\t}\n")
	return format.Source([]byte(out.String()))
}

func renderIDs(out *strings.Builder, ids []schema.EntryID) {
	if ids == nil {
		out.WriteString("nil")
		return
	}
	out.WriteString("[]schema.EntryID{")
	for _, id := range ids {
		key, ok := denominatorKey(id)
		if !ok {
			// render() cannot return an error from this small helper; the
			// generated catalog itself is the authority and Build has already
			// rejected unknown IDs. Keep malformed output impossible by using
			// the identity bytes as a canonical literal fallback.
			fmt.Fprintf(out, "schema.EntryID{%s},", byteLiteral(id))
			continue
		}
		fmt.Fprintf(out, "schema.NewEntryID(schema.SurfaceKindDenominator, schema.Key(%q)),", key)
	}
	out.WriteString("}")
}

func denominatorKey(id schema.EntryID) (string, bool) {
	for _, entry := range denominatorEntries() {
		if entry.ID() == id {
			return string(entry.Key()), true
		}
	}
	return "", false
}

func denominatorEntries() []*denominator.RelationEntry {
	return denominator.GeneratedRelationEntries()
}

func byteLiteral(id schema.EntryID) string {
	var out strings.Builder
	for index, value := range id {
		if index != 0 {
			out.WriteString(",")
		}
		fmt.Fprintf(&out, "0x%02x", value)
	}
	return out.String()
}
