package programsupply

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
)

// Generate rebuilds or checks the cold Program-supply evidence source.
func Generate(out string, check bool) error {
	evidence, err := Build()
	if err != nil {
		return err
	}
	rendered, err := render(evidence)
	if err != nil {
		return err
	}
	current, readErr := os.ReadFile(out)
	if check {
		if readErr != nil || !bytes.Equal(current, rendered) {
			return fmt.Errorf("Program supply: evidence is stale")
		}
		return nil
	}
	if err := os.WriteFile(out, rendered, 0o644); err != nil {
		return fmt.Errorf("Program supply: write evidence: %w", err)
	}
	return nil
}

func render(e Evidence) ([]byte, error) {
	var out strings.Builder
	out.WriteString("// Code generated by Program supply evidence; DO NOT EDIT.\n\npackage programsupply\n\n")
	out.WriteString("import (\n\tflowkind \"github.com/wippyai/go-lua/analysis/program/flow/kind\"\n\t\"github.com/wippyai/go-lua/analysis/lua/internal/grammarproof/requirements/binder\"\n\t\"github.com/wippyai/go-lua/analysis/lua/internal/grammarproof/requirements/programlaw\"\n\t\"github.com/wippyai/go-lua/analysis/lua/internal/grammarproof/requirements/staticlaw\"\n\t\"github.com/wippyai/go-lua/analysis/program/semanticsource\"\n)\n\n")
	fmt.Fprintf(&out, "func init() {\n\tGenerated = Evidence{\n\t\tSchemaDigest: %q,\n\t\tDigest: %q,\n", e.SchemaDigest, e.Digest)
	out.WriteString("\t\tProgramLaws: []ProgramLawRow{\n")
	for _, row := range e.ProgramLaws {
		fmt.Fprintf(&out, "\t\t\t{Requirement: programlaw.Requirement{Site: programlaw.Site(%d), Unary: flowkind.UnaryOp(%d), Binary: flowkind.BinaryOp(%d), Select: flowkind.SelectOp(%d), Call: programlaw.CallMode(%d), Values: programlaw.ValuesMode(%d), Outcome: flowkind.OutcomeKind(%d)}, Terminals: ", row.Requirement.Site, row.Requirement.Unary, row.Requirement.Binary, row.Requirement.Select, row.Requirement.Call, row.Requirement.Values, row.Requirement.Outcome)
		renderReferences(&out, row.Terminals)
		out.WriteString("},\n")
	}
	out.WriteString("\t\t},\n\t\tStaticLaws: []StaticLawRow{\n")
	for _, row := range e.StaticLaws {
		fmt.Fprintf(&out, "\t\t\t{Family: staticlaw.Family(%d), Terminals: ", row.Family)
		renderReferences(&out, row.Terminals)
		out.WriteString("},\n")
	}
	out.WriteString("\t\t},\n\t\tBinderLaws: []BinderRow{\n")
	for _, row := range e.BinderLaws {
		fmt.Fprintf(&out, "\t\t\t{Requirement: binder.Requirement{Transition: binder.Transition(%d)}, Positive: ", row.Requirement.Transition)
		renderReferences(&out, row.Positive)
		out.WriteString(", Forbidden: ")
		renderReferences(&out, row.Forbidden)
		out.WriteString("},\n")
	}
	out.WriteString("\t\t},\n\t}\n}\n")
	return format.Source([]byte(out.String()))
}

func renderReferences(out *strings.Builder, references []Reference) {
	if references == nil {
		out.WriteString("nil")
		return
	}
	out.WriteString("[]Reference{")
	for _, item := range references {
		fmt.Fprintf(out, "{Origin: semanticsource.Origin(%d), Facet: semanticsource.Facet(%d), Revision: semanticsource.Revision(%d)},", item.Origin, item.Facet, item.Revision)
	}
	out.WriteString("}")
}
