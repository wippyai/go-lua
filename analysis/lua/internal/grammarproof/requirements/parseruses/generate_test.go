package parseruses

import (
	"bytes"
	"testing"
)

func TestParserUsesGeneratorRendersDeterministicSemanticArtifact(t *testing.T) {
	products := testProducts()
	evidence, err := Build(products, testCensus(products))
	if err != nil {
		t.Fatal(err)
	}
	first, err := render(evidence)
	if err != nil {
		t.Fatal(err)
	}
	second, err := render(evidence)
	if err != nil {
		t.Fatal(err)
	}
	if len(first) == 0 || !bytes.Equal(first, second) || !bytes.Contains(first, []byte("Code generated by parser-use evidence")) {
		t.Fatal("parser-use generator output is not a deterministic semantic artifact")
	}
}
