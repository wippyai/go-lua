// Generate rebuilds or checks the cold parser-use artifact from an already
// sealed parser-products artifact. It cannot discover a root or inspect
// source; callers must inject the proof they want this artifact to consume.
func Generate(products parserproducts.Evidence, out string, check bool) error {
	evidence, err := Build(products)
	if err != nil {
		return err
	}
	rendered, err := render(evidence)
	if err != nil {
		return err
	}
	current, readErr := os.ReadFile(out)
	if check {
		if readErr != nil || !bytes.Equal(current, rendered) {
			return fmt.Errorf("parser uses: evidence is stale")
		}
		return nil
	}
	if err := os.WriteFile(out, rendered, 0o644); err != nil {
		return fmt.Errorf("parser uses: write evidence: %w", err)
	}
	return nil
}

func render(e Evidence) ([]byte, error) {
	var out strings.Builder
	out.WriteString("// Code generated by parser-use evidence; DO NOT EDIT.\n\npackage parseruses\n\n")
	out.WriteString("import (\n")
	out.WriteString("\t\"github.com/wippyai/go-lua/analysis/lua/internal/grammarproof/astcodec\"\n")
	out.WriteString("\t\"github.com/wippyai/go-lua/analysis/lua/internal/grammarproof/requirements/occurrence\"\n")
	out.WriteString("\t\"github.com/wippyai/go-lua/analysis/lua/internal/grammarproof/requirements/parserproducts\"\n")
	out.WriteString(")\n\nvar Generated = Evidence{\n")
	writeQuoted(&out, "\t\t", "ProductsDigest", e.ProductsDigest)
	writeQuoted(&out, "\t\t", "Digest", e.Digest)
	renderSlots(&out, e.UseSlots)
	renderDirect(&out, e.UsePaths)
	renderHelpers(&out, e.HelperUsePaths)
	renderMutations(&out, e.MutationUsePaths)
	renderTails(&out, e.ValuesTails)
	renderLValues(&out, e.LValuePaths)
	out.WriteString("\t}\n")
	return []byte(out.String()), nil
}

func renderSlots(out *strings.Builder, rows []UseSlot) {
	out.WriteString("\t\tUseSlots: []UseSlot{\n")
	for _, row := range rows {
		out.WriteString("\t\t\t{\n")
		writeQuoted(out, "\t\t\t\t", "ParentForm", row.ParentForm)
		writeQuoted(out, "\t\t\t\t", "ParentField", row.ParentField)
		writeTyped(out, "\t\t\t\t", "ParentContext", "occurrence.Context", uint64(row.ParentContext))
		writeTyped(out, "\t\t\t\t", "Role", "UseRole", uint64(row.Role))
		writeQuoted(out, "\t\t\t\t", "ChildType", row.ChildType)
		writeTyped(out, "\t\t\t\t", "Cardinality", "astcodec.FieldState", uint64(row.Cardinality))
		writeTyped(out, "\t\t\t\t", "Target", "ProgramUseClass", uint64(row.Target))
		writeTyped(out, "\t\t\t\t", "Disposition", "parserproducts.Disposition", uint64(row.Disposition))
		writeQuoted(out, "\t\t\t\t", "Source", row.Source)
		writeTyped(out, "\t\t\t\t", "ParserLaw", "occurrence.ParserLaw", uint64(row.ParserLaw))
		out.WriteString("\t\t\t},\n")
	}
	out.WriteString("\t\t},\n")
}

func renderDirect(out *strings.Builder, rows []UsePath) {
	out.WriteString("\t\tUsePaths: []UsePath{\n")
	for _, row := range rows {
		out.WriteString("\t\t\t{\n")
		writeQuoted(out, "\t\t\t\t", "ParentProduction", row.ParentProduction)
		writeTyped(out, "\t\t\t\t", "ParentOrdinal", "", uint64(row.ParentOrdinal))
		writeQuoted(out, "\t\t\t\t", "ParentForm", row.ParentForm)
		writeQuoted(out, "\t\t\t\t", "ParentField", row.ParentField)
		writeTyped(out, "\t\t\t\t", "Term", "parserproducts.ActionTermID", uint64(row.Term))
		writeAxesSource(out, row.Role, row.Child, row.Target, row.Open, row.Table, row.LValue, row.Values)
		out.WriteString("\t\t\t},\n")
	}
	out.WriteString("\t\t},\n")
}

func renderHelpers(out *strings.Builder, rows []HelperUsePath) {
	out.WriteString("\t\tHelperUsePaths: []HelperUsePath{\n")
	for _, row := range rows {
		out.WriteString("\t\t\t{\n")
		writeQuoted(out, "\t\t\t\t", "Production", row.Production)
		writeApplicationsSource(out, row.Applications)
		writeTyped(out, "\t\t\t\t", "Helper", "parserproducts.ActionSymbolID", uint64(row.Helper))
		writeTyped(out, "\t\t\t\t", "Ordinal", "", uint64(row.Ordinal))
		writeQuoted(out, "\t\t\t\t", "ParentForm", row.ParentForm)
		writeQuoted(out, "\t\t\t\t", "ParentField", row.ParentField)
		writeInstanceSource(out, row.Instance)
		writeAxesSource(out, row.Role, row.Child, row.Target, row.Open, row.Table, row.LValue, row.Values)
		out.WriteString("\t\t\t},\n")
	}
	out.WriteString("\t\t},\n")
}

func renderMutations(out *strings.Builder, rows []MutationUsePath) {
	out.WriteString("\t\tMutationUsePaths: []MutationUsePath{\n")
	for _, row := range rows {
		out.WriteString("\t\t\t{\n")
		writeQuoted(out, "\t\t\t\t", "Production", row.Production)
		writeTyped(out, "\t\t\t\t", "Ordinal", "", uint64(row.Ordinal))
		writeEditSource(out, row.Edit)
		writeMutationAxes(out, row.Role, row.Child, row.Target, row.Open, row.Table, row.LValue)
		out.WriteString("\t\t\t},\n")
	}
	out.WriteString("\t\t},\n")
}

func renderTails(out *strings.Builder, rows []ValuesTail) {
	out.WriteString("\t\tValuesTails: []ValuesTail{\n")
	for _, row := range rows {
		out.WriteString("\t\t\t{\n")
		writeSequenceCoordinateSource(out, row.Sequence)
		writeTyped(out, "\t\t\t\t", "Position", "ValuesPosition", uint64(row.Position))
		writeTyped(out, "\t\t\t\t", "Successor", "", uint64(row.Successor))
		out.WriteString("\t\t\t},\n")
	}
	out.WriteString("\t\t},\n")
}

func renderLValues(out *strings.Builder, rows []LValuePath) {
	out.WriteString("\t\tLValuePaths: []LValuePath{\n")
	for _, row := range rows {
		out.WriteString("\t\t\t{\n")
		writeQuoted(out, "\t\t\t\t", "SeedProduction", row.SeedProduction)
		writeTyped(out, "\t\t\t\t", "SeedOrdinal", "", uint64(row.SeedOrdinal))
		writeSequenceCoordinateSource(out, row.Sequence)
		writeQuoted(out, "\t\t\t\t", "TerminalProduction", row.TerminalProduction)
		writeTyped(out, "\t\t\t\t", "TerminalOrdinal", "", uint64(row.TerminalOrdinal))
		writeQuoted(out, "\t\t\t\t", "TerminalForm", row.TerminalForm)
		out.WriteString("\t\t\t},\n")
	}
	out.WriteString("\t\t},\n")
}

func writeSequenceCoordinateSource(out *strings.Builder, coordinate SequenceCoordinate) {
	out.WriteString("\t\t\t\tSequence: SequenceCoordinate{\n")
	writeQuoted(out, "\t\t\t\t\t", "Production", coordinate.Production)
	writeQuoted(out, "\t\t\t\t\t", "Tag", coordinate.Tag)
	writeQuoted(out, "\t\t\t\t\t", "Field", coordinate.Field)
	writeTyped(out, "\t\t\t\t\t", "Segment", "", uint64(coordinate.Segment))
	out.WriteString("\t\t\t\t},\n")
}

func writeQuoted(out *strings.Builder, indent, name, value string) {
	fmt.Fprintf(out, "%s%s: %q,\n", indent, name, value)
}

func writeTyped(out *strings.Builder, indent, name, typ string, value uint64) {
	if typ == "" {
		fmt.Fprintf(out, "%s%s: %d,\n", indent, name, value)
		return
	}
	fmt.Fprintf(out, "%s%s: %s(%d),\n", indent, name, typ, value)
}

func writeApplicationsSource(out *strings.Builder, rows []uint16) {
	out.WriteString("\t\t\t\tApplications: []uint16{")
	for _, row := range rows {
		fmt.Fprintf(out, "%d,", row)
	}
	out.WriteString("},\n")
}

func writeInstanceSource(out *strings.Builder, instance parserproducts.TermInstance) {
	out.WriteString("\t\t\t\tInstance: parserproducts.TermInstance{\n")
	writeTyped(out, "\t\t\t\t\t", "CallerScope", "parserproducts.ActionScopeID", uint64(instance.CallerScope))
	writeTyped(out, "\t\t\t\t\t", "HelperScope", "parserproducts.ActionScopeID", uint64(instance.HelperScope))
	writeTyped(out, "\t\t\t\t\t", "Root", "parserproducts.ActionTermID", uint64(instance.Root))
	out.WriteString("\t\t\t\t\tActuals: []parserproducts.ActionTermID{")
	for _, actual := range instance.Actuals {
		fmt.Fprintf(out, "parserproducts.ActionTermID(%d),", actual)
	}
	out.WriteString("},\n\t\t\t\t},\n")
}

func writeEditSource(out *strings.Builder, edit parserproducts.Edit) {
	out.WriteString("\t\t\t\tEdit: parserproducts.Edit{\n")
	writeTyped(out, "\t\t\t\t\t", "Kind", "parserproducts.EditKind", uint64(edit.Kind))
	if edit.Guard.Atoms == nil {
		out.WriteString("\t\t\t\t\tGuard: parserproducts.Guard{},\n")
	} else {
		out.WriteString("\t\t\t\t\tGuard: parserproducts.Guard{Atoms: []parserproducts.GuardAtom{\n")
		for _, atom := range edit.Guard.Atoms {
			out.WriteString("\t\t\t\t\t\t{")
			fmt.Fprintf(out, "Kind: parserproducts.GuardAtomKind(%d), Negated: %t, Term: parserproducts.ActionTermID(%d), Constant: parserproducts.ActionSymbolID(%d), SetStart: %d, SetCount: %d, ParseClass: parserproducts.NumberParseClass(%d)", atom.Kind, atom.Negated, atom.Term, atom.Constant, atom.SetStart, atom.SetCount, atom.ParseClass)
			out.WriteString("},\n")
		}
		out.WriteString("\t\t\t\t\t}},\n")
	}
	out.WriteString("\t\t\t\t\tPlace: parserproducts.Place{\n")
	writeTyped(out, "\t\t\t\t\t\t", "Scope", "parserproducts.ActionScopeID", uint64(edit.Place.Scope))
	writeTyped(out, "\t\t\t\t\t\t", "Root", "parserproducts.PlaceRoot", uint64(edit.Place.Root))
	writeTyped(out, "\t\t\t\t\t\t", "Slot", "", uint64(edit.Place.Slot))
	writeTyped(out, "\t\t\t\t\t\t", "StepStart", "", uint64(edit.Place.StepStart))
	writeTyped(out, "\t\t\t\t\t\t", "StepCount", "", uint64(edit.Place.StepCount))
	out.WriteString("\t\t\t\t\t},\n")
	writeTyped(out, "\t\t\t\t\t", "Value", "parserproducts.ActionTermID", uint64(edit.Value))
	out.WriteString("\t\t\t\t},\n")
}

func writeAxesSource(out *strings.Builder, role UseRole, child ChildClass, target ProgramUseClass, open OpenAxis, table TableAxis, lvalue LValueAxis, values ValuesPosition) {
	writeTyped(out, "\t\t\t\t", "Role", "UseRole", uint64(role))
	writeTyped(out, "\t\t\t\t", "Child", "ChildClass", uint64(child))
	writeTyped(out, "\t\t\t\t", "Target", "ProgramUseClass", uint64(target))
	writeTyped(out, "\t\t\t\t", "Open", "OpenAxis", uint64(open))
	writeTyped(out, "\t\t\t\t", "Table", "TableAxis", uint64(table))
	writeTyped(out, "\t\t\t\t", "LValue", "LValueAxis", uint64(lvalue))
	writeTyped(out, "\t\t\t\t", "Values", "ValuesPosition", uint64(values))
}

func writeMutationAxes(out *strings.Builder, role UseRole, child ChildClass, target ProgramUseClass, open OpenAxis, table TableAxis, lvalue LValueAxis) {
	writeTyped(out, "\t\t\t\t", "Role", "UseRole", uint64(role))
	writeTyped(out, "\t\t\t\t", "Child", "ChildClass", uint64(child))
	writeTyped(out, "\t\t\t\t", "Target", "ProgramUseClass", uint64(target))
	writeTyped(out, "\t\t\t\t", "Open", "OpenAxis", uint64(open))
	writeTyped(out, "\t\t\t\t", "Table", "TableAxis", uint64(table))
	writeTyped(out, "\t\t\t\t", "LValue", "LValueAxis", uint64(lvalue))
}
