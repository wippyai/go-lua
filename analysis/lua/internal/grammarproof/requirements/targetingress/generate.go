package targetingress

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
)

// Generate rebuilds or checks the cold Target ingress evidence source.
func Generate(out string, check bool) error {
	evidence, err := Build()
	if err != nil {
		return err
	}
	rendered, err := render(evidence)
	if err != nil {
		return err
	}
	current, readErr := os.ReadFile(out)
	if check {
		if readErr != nil || !bytes.Equal(current, rendered) {
			return fmt.Errorf("Target ingress requirements: evidence is stale")
		}
		return nil
	}
	if err := os.WriteFile(out, rendered, 0o644); err != nil {
		return fmt.Errorf("Target ingress requirements: write evidence: %w", err)
	}
	return nil
}

func render(e Evidence) ([]byte, error) {
	var out strings.Builder
	out.WriteString("// Code generated by Target ingress evidence; DO NOT EDIT.\n\npackage targetingress\n\n")
	out.WriteString("import (\n\t\"github.com/wippyai/go-lua/analysis/program/relations\"\n\t\"github.com/wippyai/go-lua/analysis/program/semanticsource\"\n)\n\n")
	fmt.Fprintf(&out, "func init() {\n\tGenerated = Evidence{\n\t\tSchemaDigest: %q,\n\t\tDigest: %q,\n\t\tRows: []Row{\n", e.SchemaDigest, e.Digest)
	for _, row := range e.Rows {
		fmt.Fprintf(&out, "\t\t\t{Relation: Reference{Origin: semanticsource.Origin(%d), Facet: semanticsource.Facet(%d), Revision: semanticsource.Revision(%d)}, Owner: relations.Owner(%d), Form: relations.Form(%d), Ingress: []Reference{", row.Relation.Origin, row.Relation.Facet, row.Relation.Revision, row.Owner, row.Form)
		for index, ingress := range row.Ingress {
			if index != 0 {
				out.WriteString(", ")
			}
			fmt.Fprintf(&out, "{Origin: semanticsource.Origin(%d), Facet: semanticsource.Facet(%d), Revision: semanticsource.Revision(%d)}", ingress.Origin, ingress.Facet, ingress.Revision)
		}
		out.WriteString("}},\n")
	}
	out.WriteString("\t\t},\n\t}\n}\n")
	return format.Source([]byte(out.String()))
}
